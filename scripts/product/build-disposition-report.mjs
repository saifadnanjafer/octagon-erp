#!/usr/bin/env node
/*
 * Product Recovery 1 — Phase J: disposition report.
 *
 * Compares the CURRENT docs/product/PAGE_FUNCTIONAL_LEDGER.json /
 * PAGE_REALITY_LEDGER.json against the BEFORE baseline this recovery wave
 * started from (docs/product/PAGE_FUNCTIONAL_LEDGER.md as generated
 * 2026-08-09T07:00:12Z, the snapshot read at the start of this session,
 * before any fix in this pass landed). The before-numbers below are a
 * recorded historical fact, not re-derived, because the ledger this script
 * reads is regenerated in place and does not keep its own history.
 *
 * Output: docs/product/PAGE_DISPOSITION_REPORT.md
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const P = (...parts) => path.join(root, ...parts);
const readJson = (file, fallback = null) => {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return fallback; }
};

const ledger = readJson(P('docs', 'product', 'PAGE_FUNCTIONAL_LEDGER.json'));
const reality = readJson(P('docs', 'product', 'PAGE_REALITY_LEDGER.json'));
if (!ledger || !reality) throw new Error('Both PAGE_FUNCTIONAL_LEDGER.json and PAGE_REALITY_LEDGER.json are required');

const BEFORE = {
  generatedAt: '2026-08-09T07:00:12.405Z',
  totalPrimaryPages: 231,
  functionalStateCounts: { USABLE: 113, STRONG: 80, THIN: 31, BROKEN: 7 },
  deadEndCount: 2,
};

const after = {
  totalPrimaryPages: ledger.totalPrimaryPages,
  functionalStateCounts: ledger.functionalStateCounts,
  deadEndCount: ledger.deadEndCount,
};

const emptinessCounts = reality.emptinessCauseCounts || {};
const dispositionCounts = reality.recommendedDispositionCounts || {};

const cell = (value) => String(value ?? '—').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim() || '—';
const clip = (value, max) => { const text = cell(value); return text.length > max ? `${text.slice(0, max - 1)}…` : text; };

const md = [];
md.push('# Page Disposition Report — Product Recovery 1');
md.push('');
md.push('Generated by `scripts/product/build-disposition-report.mjs` — do not hand-edit.');
md.push(`Before: docs/product/PAGE_FUNCTIONAL_LEDGER.md as generated ${BEFORE.generatedAt} (session start).`);
md.push(`After: docs/product/PAGE_FUNCTIONAL_LEDGER.json as generated ${ledger.generatedAt} (current).`);
md.push('');
md.push('## Primary page count');
md.push('');
md.push('| | Before | After |');
md.push('|---|---|---|');
md.push(`| Primary workspaces | ${BEFORE.totalPrimaryPages} | ${after.totalPrimaryPages} |`);
md.push(`| Moved to tab this pass | — | 0 (5 prior consolidations already in place before this session; see docs/navigation/OWNER_CONSOLIDATION_DECISIONS.md; 2 more A-class and 10 B-class candidates await owner sign-off — see OWNER_PRODUCT_DECISIONS.md) |`);
md.push(`| Moved to dialog/action this pass | — | 0 |`);
md.push(`| Hidden/internal this pass | — | 0 |`);
md.push(`| Retired this pass | — | 0 |`);
md.push(`| **Capabilities lost** | — | **0** |`);
md.push('');
md.push('No navigation consolidation was executed in this pass. Every candidate found');
md.push('(PAGE_OVERLAP_MATRIX.md, OWNER_PRODUCT_DECISIONS.md) needs an owner call on intent');
md.push('before a page id changes meaning for whoever already has it bookmarked — see');
md.push('OWNER_PRODUCT_DECISIONS.md. This pass focused on making the existing 231 honest:');
md.push('classifying every one with evidence and fixing what runtime evidence proved broken.');
md.push('');
md.push('## Functional state');
md.push('');
md.push('| State | Before | After | Δ |');
md.push('|---|---|---|---|');
['STRONG', 'USABLE', 'THIN', 'BROKEN'].forEach((state) => {
  const before = BEFORE.functionalStateCounts[state] || 0;
  const afterCount = after.functionalStateCounts[state] || 0;
  const delta = afterCount - before;
  md.push(`| ${state} | ${before} | ${afterCount} | ${delta > 0 ? '+' : ''}${delta} |`);
});
md.push(`| Dead ends (content, no action, no link) | ${BEFORE.deadEndCount} | ${after.deadEndCount} | ${after.deadEndCount - BEFORE.deadEndCount > 0 ? '+' : ''}${after.deadEndCount - BEFORE.deadEndCount} |`);
md.push('');

md.push('## Fixes landed this pass');
md.push('');
md.push('| Fix | Root cause | Pages affected |');
md.push('|---|---|---|');
md.push('| `pick_task_queue` crash guard (modules/build09-pick-task-queue-workspace.js) | `allRows` used before first assignment when `onActivate` threw on a permission denial — the error panel rendered behind a page that had already crashed | 1 (`pick_task_queue`) |');
md.push('| `build12` overview `scoped()` tenantId fix (platform/build12/index.mjs) | Every `scoped()` call in the combined overview resource omitted `tenantId`, shifting each positional arg left by one — the order string landed in the tenantId slot and the limit number in the order slot, producing an invalid `ORDER BY <number>` SQLite throws on | 3 (`ai_overview`, `marketing_overview`, `people_development_overview`) |');
md.push('| `build12` per-resource order-column fix (platform/build12/index.mjs) | The generic query-map path defaulted every resource to `ORDER BY created_at DESC`; `people_competencies` only has `updated_at` and `build12_event_registrations` only has `registered_at` — both threw a 500 on every request | 3 (`competency_profiles`, `event_checkin`, `event_registrations`) |');
md.push('| WMS/shopfloor/quality `:view` permission registration (database/migrations/090, scripts/review/roles.mjs) | 16 of the 20 permission tokens `platform/api/build09.mjs` `BUILD09_RESOURCE_PERMISSIONS` requires for `GET /api/v1/wms/*` were never registered in `authorization_permissions` at all — `registry.assertKnown()` fails closed on an unregistered token regardless of what any role is granted, so no role (review or production) could ever pass these checks | 18 pages — see PAGE_RUNTIME_ERROR_LEDGER.md for the full list |');
md.push('');

md.push('## Emptiness cause distribution (current)');
md.push('');
md.push('| Cause | Pages |');
md.push('|---|---|');
Object.entries(emptinessCounts).sort((a, b) => b[1] - a[1]).forEach(([cause, count]) => md.push(`| ${cause} | ${count} |`));
if (!Object.keys(emptinessCounts).length) md.push('| _(none — every THIN/BROKEN page from the previous pass has been fixed or reclassified)_ | |');
md.push('');
md.push('## Recommended disposition (current)');
md.push('');
md.push('| Disposition | Pages |');
md.push('|---|---|');
Object.entries(dispositionCounts).sort((a, b) => b[1] - a[1]).forEach(([d, count]) => md.push(`| ${d} | ${count} |`));
md.push('');

const remaining = reality.rows.filter((row) => row.emptinessCause);
if (remaining.length) {
  md.push(`## Pages still needing attention (${remaining.length})`);
  md.push('');
  md.push('| Page | Priority | Cause | Disposition |');
  md.push('|---|---|---|---|');
  remaining.sort((a, b) => (a.reviewPriority || '').localeCompare(b.reviewPriority || '')).forEach((row) => {
    md.push(`| \`${row.pageId}\` | ${cell(row.reviewPriority)} | ${clip(row.emptinessCause, 60)} | ${clip(row.recommendedDisposition, 60)} |`);
  });
  md.push('');
}

md.push('## Golden Workshop Dataset coverage');
md.push('');
md.push('Strong, cross-linked coverage: Workshop Jobs (11 rows covering every board state —');
md.push('new/backlog, due-today, overdue+SLA-breached, blocked, design-approval-pending,');
md.push('material-shortage+SLA-breached, active-production, quality-hold+SLA-breached,');
md.push('rework, ready-for-delivery, closed), Warehouse (receiving+discrepancy, lot-controlled');
md.push('+near-expiration stock, pick tasks, replenishment proposal), Production (BOM, work');
md.push('centers, work orders, a machine-breakdown downtime event), Quality (an NCR), and the');
md.push('Commercial/SaaS platform layer.');
md.push('');
md.push('**Gap found**: zero fixture rows for customers, sales quotations, or suppliers/');
md.push('purchase orders, despite the canonical schema existing for all three');
md.push('(`database/migrations/039_crm_sales_contracts_commissions.mjs`,');
md.push('`040_suppliers_procurement_threeway_match.mjs`). This is why `sales_price_lists`');
md.push('and `supplier_portal` currently read as "no domain implementation" — the schema is');
md.push('there, the fixture never points a customer or quotation at it. See');
md.push('OWNER_PRODUCT_DECISIONS.md §4 for the scoping call.');
md.push('');

fs.writeFileSync(P('docs', 'product', 'PAGE_DISPOSITION_REPORT.md'), `${md.join('\n')}\n`, 'utf8');
console.log(`Disposition report -> docs/product/PAGE_DISPOSITION_REPORT.md`);
console.log(`  before: ${JSON.stringify(BEFORE.functionalStateCounts)}`);
console.log(`  after:  ${JSON.stringify(after.functionalStateCounts)}`);
