#!/usr/bin/env node
/*
 * Product Recovery 1 — Phase J: the human-readable product map.
 *
 * DOMAIN -> WORKSPACE GROUP -> PRIMARY WORKSPACE -> MAJOR BUSINESS TASKS,
 * in plain language, no BUILD numbers, no migration terminology — generated
 * from docs/product/PAGE_REALITY_LEDGER.json rather than hand-authored,
 * because a 231-page map hand-written once will be wrong within a week and
 * nobody will remember to update it. Regenerate with `npm run
 * product:product-map` after any ledger refresh.
 *
 * Consolidation is shown where this pass has real evidence for it: the five
 * owner-approved tab/alias reclassifications already on record
 * (docs/navigation/OWNER_CONSOLIDATION_DECISIONS.md) are nested under their
 * canonical parent instead of listed as their own workspace. Everything else
 * is listed as its own primary workspace — this file does not invent a tab
 * structure inside a workspace it has no evidence for.
 *
 * Output: docs/product/OCTAGON_PRODUCT_MAP.md
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..');
const P = (...parts) => path.join(root, ...parts);
const readJson = (file, fallback = null) => {
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return fallback; }
};

const reality = readJson(P('docs', 'product', 'PAGE_REALITY_LEDGER.json'));
if (!reality) throw new Error('docs/product/PAGE_REALITY_LEDGER.json is required — run `npm run product:reality-ledger` first');

// pageId -> canonical parent id, from docs/navigation/OWNER_CONSOLIDATION_DECISIONS.md
const KNOWN_TABS = {
  calculator: 'timesheet', kanban: 'task_manager', locations: 'warehouses', workshop_tv: 'task_manager',
};
const KNOWN_ALIASES = { pos_deepening: 'pos' };

const DOMAIN_NAMES = {
  core: 'Daily Operations', admin: 'Administration', commercial: 'Commercial & Sales',
  finance: 'Finance', ops: 'Workshop & Operations', resources: 'Resources & Assets', intelligence: 'Intelligence & AI',
};
const humanize = (slug) => (slug || '').split('_').slice(1).join(' ').replace(/\b\w/g, (c) => c.toUpperCase()) || slug;

const cleanPurpose = (purpose) => (purpose || '').replace(/\s*\(risk:[^)]*\)\s*$/, '').trim();
const cleanActions = (actions) => {
  if (!actions || actions === 'none rendered' || actions.startsWith('NOT_OBSERVED')) return null;
  // Some scraped control labels are multi-line (e.g. a calendar day-cell
  // button whose innerText is "1\nSat\npredicted\n0\n..."); collapse
  // whitespace BEFORE the length filter, since a multi-line label can still
  // measure short in raw .length while rendering as several broken lines of
  // markdown once joined.
  const items = actions.split('|').map((a) => a.replace(/\s+/g, ' ').trim()).filter(Boolean);
  const deduped = [...new Set(items)].filter((a) => a.length < 45 && a.length > 0);
  return deduped.slice(0, 8);
};

const rows = reality.rows.filter((row) => !KNOWN_TABS[row.pageId] && !KNOWN_ALIASES[row.pageId]);
const byDomain = new Map();
rows.forEach((row) => {
  if (!byDomain.has(row.domain)) byDomain.set(row.domain, new Map());
  const groups = byDomain.get(row.domain);
  if (!groups.has(row.sidebarGroup)) groups.set(row.sidebarGroup, []);
  groups.get(row.sidebarGroup).push(row);
});

const tabsByParent = new Map();
Object.entries(KNOWN_TABS).forEach(([child, parent]) => {
  if (!tabsByParent.has(parent)) tabsByParent.set(parent, []);
  tabsByParent.get(parent).push(child);
});
const aliasesByParent = new Map();
Object.entries(KNOWN_ALIASES).forEach(([child, parent]) => {
  if (!aliasesByParent.has(parent)) aliasesByParent.set(parent, []);
  aliasesByParent.get(parent).push(child);
});

const md = [];
md.push('# Octagon Product Map');
md.push('');
md.push('Generated by `scripts/product/build-product-map.mjs` from docs/product/PAGE_REALITY_LEDGER.json');
md.push(`(built on ${reality.builtOn}) — do not hand-edit, regenerate after any ledger refresh.`);
md.push('');
md.push('This is the plain-language map of what Octagon actually does today: what a user');
md.push('opens, what they can do there, and what happens next. Workspaces marked with a');
md.push('status tag are not yet doing their job — see PAGE_DISPOSITION_REPORT.md for why');
md.push('and what fixing them means.');
md.push('');

const domainOrder = ['core', 'commercial', 'finance', 'ops', 'resources', 'intelligence', 'admin'];
domainOrder.filter((d) => byDomain.has(d)).forEach((domain) => {
  const groups = byDomain.get(domain);
  md.push(`## ${DOMAIN_NAMES[domain] || domain}`);
  md.push('');
  [...groups.keys()].sort().forEach((groupKey) => {
    const pages = groups.get(groupKey).sort((a, b) => a.labelEn.localeCompare(b.labelEn));
    md.push(`### ${humanize(groupKey) || groupKey}`);
    md.push('');
    pages.forEach((row) => {
      const tabs = tabsByParent.get(row.pageId) || [];
      const aliases = aliasesByParent.get(row.pageId) || [];
      const statusTag = row.functionalState === 'STRONG' || row.functionalState === 'USABLE' ? '' : ` _(${row.functionalState.toLowerCase()}${row.emptinessCause ? ` — ${row.emptinessCause.split(' — ')[0]}` : ''})_`;
      md.push(`**${row.labelEn}**${row.labelAr && row.labelAr !== row.labelEn ? ` (${row.labelAr})` : ''}${statusTag}`);
      const purpose = cleanPurpose(row.businessPurpose);
      if (purpose) md.push(`  ${purpose}.`);
      const actions = cleanActions(row.actionsAvailable);
      if (actions) md.push(`  Tasks: ${actions.join(', ')}.`);
      if (row.downstreamWorkflow && !row.downstreamWorkflow.startsWith('none') && !row.downstreamWorkflow.startsWith('NOT_OBSERVED')) {
        md.push(`  Hands off to: ${row.downstreamWorkflow}.`);
      }
      if (tabs.length) md.push(`  Includes tabs: ${tabs.join(', ')}.`);
      if (aliases.length) md.push(`  Also reachable as: ${aliases.join(', ')} (same workspace).`);
      md.push('');
    });
  });
});

fs.writeFileSync(P('docs', 'product', 'OCTAGON_PRODUCT_MAP.md'), `${md.join('\n')}\n`, 'utf8');
console.log(`Product map: ${rows.length} primary workspaces across ${byDomain.size} domains -> docs/product/OCTAGON_PRODUCT_MAP.md`);
